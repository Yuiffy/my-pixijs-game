const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const ts = require('typescript');
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, file);
const { SAVE_KEY } = require('../src/components/liuzhou/world.ts');
const { terrainHeight } = require('../src/components/liuzhou/terrain.ts');
const u = require('../src/components/liuzhou/underground.ts');
const { chromium } = require(require.resolve('playwright', { paths: [process.cwd(), path.join(os.homedir(), '.codex/skills/develop-web-game')] }));
const { quietContext } = require('./lib/liuzhou-test-browser.cjs');
const { inspectPng } = require('./lib/autochess-screenshot.cjs');
const base = process.env.LIUZHOU_BASE_URL || 'http://127.0.0.1:4133';
const out = process.env.LIUZHOU_QA_DIR || '.tmp/liuzhou-underground-dev';
const report = { fixture: 'legitimate ground save just outside the first stair; all subsequent travel uses ordinary input and Rapier', errors: [], captures: [], passed: false };
(async () => {
  assert.equal((await fetch(`${base}/game/liuzhou`, { signal: AbortSignal.timeout(60000) })).status, 200);
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--mute-audio', '--disable-speech-api'] });
  try {
    const context = await quietContext(browser, { viewport: { width: 1440, height: 900 } });
    await context.route(/https:\/\/(pagead2\.googlesyndication\.com|hm\.baidu\.com)\//, r => r.fulfill({ body: '' }));
    const entry = u.UNDERGROUND_ENTRANCES.find(e => e.id === '1275168873');
    const yaw = Math.atan2(entry.points[1][0] - entry.top[0], entry.points[1][1] - entry.top[1]);
    const start = { x: entry.top[0] - Math.sin(yaw) * 2, z: entry.top[1] - Math.cos(yaw) * 2, angle: yaw, speed: 0 };
    await context.addInitScript(({ key, player }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 1, terrainVersion: 2, stage: 0, exploration: true, character: 'sui', player })); }, { key: SAVE_KEY, player: { ...start, y: terrainHeight(start) } });
    const page = await context.newPage();
    page.on('pageerror', e => report.errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') report.errors.push(m.text()); });
    const enter = async () => {
      await page.goto(`${base}/game/liuzhou?test=1`);
      await page.getByRole('button', { name: '自由巡览 · 快速飞行 ↗' }).waitFor({ timeout: 90000 });
      await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent.includes('自由巡览 · 快速飞行'))?.disabled, { timeout: 90000 });
      await page.evaluate(() => window.liuzhouTest.manual(true));
      await page.getByRole('button', { name: '自由巡览 · 快速飞行 ↗' }).click();
    };
    await enter();
    const capture = async (name, yaw = Math.PI, zoom = 6, pitch = 0.1) => {
      await page.evaluate(({ yaw, zoom, pitch }) => Object.assign(window.liuzhouTest.rig, { yaw, zoom, pitch, reset: true, dragged: performance.now() }), { yaw, zoom, pitch });
      await page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))));
      const file = path.join(out, `${name}.png`); const sanity = inspectPng(await page.screenshot({ path: file, fullPage: true }));
      const state = await page.evaluate(() => JSON.parse(window.render_game_to_text()));
      const dom = await page.evaluate(() => ({ canvas: [...document.querySelectorAll('canvas')].map(c => ({ width: c.width, height: c.height, calls: c.dataset.drawCalls, cameraDistance: c.dataset.cameraDistance })), playerOpacity: window.liuzhouTest.rig.avatars?.().find(a => a.id === 'player')?.opacity, undergroundLayer: !!document.querySelector('[data-underground-layer="B1"]'), width: innerWidth, scroll: document.documentElement.scrollWidth }));
      assert.equal(dom.canvas.length, 1); assert.ok(dom.canvas[0].width > 0); assert.ok(dom.scroll <= dom.width + 1);
      report.captures.push({ name, file, sanity, state, dom });
      if (name === '02-stair-landing') assert.ok(dom.playerOpacity < 0.1, `tight stair camera leaves avatar opaque: ${dom.playerOpacity}`);
      if (name === '03-concourse' || name === '04-shops') assert.ok(dom.playerOpacity > 0.99, `avatar did not return after stair: ${dom.playerOpacity}`);
      return state;
    };
    const walk = async (point, sprint = false) => {
      let best = Infinity; let stalled = 0;
      for (let n = 0; n < 500; n++) {
        const done = await page.evaluate(({ point, sprint }) => {
          const t = window.liuzhouTest; const p = t.game.player; const distance = Math.hypot(point[0] - p.x, point[1] - p.z);
          if (distance < 0.5) return true;
          const angle = Math.atan2(point[0] - p.x, point[1] - p.z); t.rig.yaw = angle;
          t.move({ forward: 1, sprint }, Math.min(60, Math.max(1, Math.floor((distance - 0.25) / (sprint ? 8.2 : 4.4) * 60))));
          return false;
        }, { point, sprint });
        if (done) return;
        const distance = await page.evaluate(point => Math.hypot(point[0] - window.liuzhouTest.game.player.x, point[1] - window.liuzhouTest.game.player.z), point);
        stalled = distance < best - 0.05 ? 0 : stalled + 1; best = Math.min(best, distance);
        if (stalled > 8) break;
      }
      throw new Error(`walk failed ${JSON.stringify({ point, state: await page.evaluate(() => JSON.parse(window.render_game_to_text())) })}`);
    };
    await capture('01-surface-entry', yaw, 8, 0.3);
    await walk(entry.points[0]); await walk(entry.points[1]);
    await capture('02-stair-landing', Math.PI, 5, 0.15);
    await walk(entry.points[2]); await walk([-595, -118]);
    const lower = await capture('03-concourse');
    assert.equal(lower.underground, 'concourse'); assert.ok(lower.player.y < 2);
    await walk([-587.858, -264.352], true);
    await capture('04-shops', 0.1, 6, 0.05);
    const nearby = u.UNDERGROUND_SHOPS.filter(s => s.z < -250 && s.z > -280 && s.side > 0).sort((a, b) => Math.abs(a.z + 264) - Math.abs(b.z + 264))[0];
    assert.ok(nearby, 'shop close view needs a source-derived bay');
    const inward = { x: Math.cos(nearby.angle) * nearby.side, z: -Math.sin(nearby.angle) * nearby.side };
    const mouth = [nearby.x - inward.x * 4.1, nearby.z - inward.z * 4.1];
    await walk(mouth);
    await capture('04b-shop-window', Math.atan2(inward.x, inward.z), 5, 0.04);
    await walk([nearby.x - inward.x * 1.3, nearby.z - inward.z * 1.3]);
    await capture('04c-inside-shop', Math.atan2(inward.x, inward.z), 2.5, 0.04);
    await walk(mouth);
    await walk([-587.858, -264.352]);
    await page.setViewportSize({ width: 390, height: 844 });
    await capture('05-mobile-concourse', Math.PI, 6, 0.08);
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.keyboard.press('Escape');
    await enter();
    const loaded = await page.evaluate(() => JSON.parse(window.render_game_to_text()));
    assert.equal(loaded.underground, 'concourse'); assert.ok(Math.abs(loaded.player.z + 264.352) < 1);
    await walk([-579.153, -442.697], true); await walk([-574.689, -531.085], true);
    await capture('06-horizontal-junction', -Math.PI / 2, 6, 0.1);
    await walk([-731.37, -531.931], true); await walk([-755.466, -522.347]);
    await walk([-760, -518]);
    const west = await capture('06b-west-branch-ceiling', 0.59, 2.5, -0.55);
    assert.equal(west.underground, 'concourse');
    assert.ok(Math.abs(west.player.y - u.undergroundLevel(west.player)) < 0.3);
    await walk([-776.022, -506.996]);
    await walk([-781.937, -517.994]);
    const exit = u.UNDERGROUND_ENTRANCES.find(e => e.id === '1275168886');
    for (const point of exit.points.slice().reverse()) await walk(point);
    const top = exit.points[0]; const next = exit.points[1]; const angle = Math.atan2(top[0] - next[0], top[1] - next[1]);
    await walk([top[0] + Math.sin(angle) * 3, top[1] + Math.cos(angle) * 3]);
    const upper = await capture('07-west-exit', angle, 8, 0.2);
    assert.equal(upper.underground, null); assert.ok(Math.abs(upper.player.y - terrainHeight(upper.player)) < 0.4);
    assert.deepEqual(report.errors, []); report.passed = true;
  } finally { await browser.close(); fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2)); }
})().catch(e => { console.error(e); process.exitCode = 1; });
