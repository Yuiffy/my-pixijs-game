const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(require.resolve('playwright', { paths: [process.cwd(), path.join(require('node:os').homedir(), '.codex/skills/develop-web-game')] }));
const { inspectPng } = require('./lib/autochess-screenshot.cjs');
const { simulate } = require('./simulate-sui-spring.cjs');
const base = process.env.SPRING_BASE_URL || 'http://127.0.0.1:4120';
const gamePath = process.env.SPRING_PATH || '/game/sui-spring/archive';
const out = process.env.SPRING_QA_DIR || '.tmp/sui-spring';
const errors = []; const captures = [];
const state = p => p.evaluate(() => JSON.parse(window.render_game_to_text()));
async function capture(p, name) {
  await p.waitForFunction(() => { const c = document.querySelector('canvas'); if (!c) return false; const b = c.getBoundingClientRect(); const host = c.parentElement.getBoundingClientRect(); return b.width <= host.width + 1 && b.height <= host.height + 1; });
  await p.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const file = path.join(out, `${name}.png`);
  const pixels = inspectPng(await p.screenshot({ path: file, fullPage: true, animations: 'disabled' }));
  const dom = await p.evaluate(() => ({ canvas: Array.from(document.querySelectorAll('canvas')).map(c => ({ w: c.width, h: c.height, cssW: c.getBoundingClientRect().width, cssH: c.getBoundingClientRect().height })), viewport: innerWidth, scroll: document.documentElement.scrollWidth, touch: matchMedia('(pointer: coarse)').matches, touchButton: document.querySelector('[aria-label="向右"]')?.getBoundingClientRect().toJSON() }));
  assert.equal(dom.canvas.length, 1); assert.ok(dom.canvas[0].cssW > 0); assert.ok(dom.scroll <= dom.viewport + 1);
  if (name === '05-mobile-landscape' || name === '06-mobile-portrait') assert.ok(dom.touchButton?.width >= 44, 'touch controls remain visible through capture and rotation');
  captures.push({ name, pixels, dom, state: await state(p) });
}
(async () => {
  assert.equal((await fetch(`${base}${gamePath}`, { signal: AbortSignal.timeout(60000) })).status, 200);
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: process.env.SPRING_HEADED !== '1', args: ['--mute-audio', '--disable-speech-api'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
    await context.route(/https:\/\/(pagead2\.googlesyndication\.com|hm\.baidu\.com)\//, r => r.fulfill({ body: '' }));
    await context.route(/\/api\/(record|demos\/visits)(\?|$)/, r => r.fulfill({ json: { success: true, count: 0 } }));
    await context.addInitScript(() => { if (window.speechSynthesis) window.speechSynthesis.speak = () => {}; });
    const p = await context.newPage();
    p.on('pageerror', e => errors.push(e.message)); p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    p.on('response', r => { if (r.status() >= 400 && /\/(games\/sui-spring|images\/autochess|_next|game\/sui-spring)/.test(r.url())) errors.push(`HTTP ${r.status()} ${r.url()}`); });
    await p.goto(`${base}${gamePath}?test=1`);
    await p.getByRole('button', { name: '把信寄出去' }).waitFor({ timeout: 60000 });
    await p.evaluate(() => window.springTest.manual(true));
    await capture(p, '01-title');
    await p.getByRole('button', { name: '把信寄出去' }).click();
    await p.evaluate(() => window.advanceTime(100));
    await capture(p, '02-start');
    await p.keyboard.down('ArrowRight'); await p.keyboard.down('Shift'); await p.keyboard.down('Space');
    await p.evaluate(() => window.advanceTime(350));
    assert.ok((await state(p)).player.x > 175); assert.ok((await state(p)).player.y < 350);
    await capture(p, '03-jump');
    await p.keyboard.up('ArrowRight'); await p.keyboard.up('Shift'); await p.keyboard.up('Space');
    await p.keyboard.press('Escape'); assert.equal((await state(p)).phase, 'paused');
    const before = await state(p); await p.evaluate(() => window.advanceTime(500)); assert.deepEqual(await state(p), before);
    await p.getByRole('button', { name: '继续冒险' }).click();
    await p.getByRole('button', { name: '图鉴' }).click(); await capture(p, '04-codex');
    await p.keyboard.press('Escape'); assert.equal((await state(p)).phase, 'playing');
    const restored = (await state(p)).player.x;
    await p.keyboard.down('ArrowRight'); await p.evaluate(() => window.advanceTime(100)); await p.keyboard.up('ArrowRight');
    assert.ok((await state(p)).player.x > restored, 'closing a dialog returns keyboard control to the game');
    if (process.env.SPRING_QUICK !== '1') {
      await p.getByRole('button', { name: '地图', exact: true }).click();
      assert.equal(await p.locator('button:disabled').count(), 3);
      await capture(p, '07-map-locked');
      await p.getByRole('button').filter({ hasText: '一封春天的信' }).click();
      for (let i = 0; i < 4; i++) {
        const run = simulate(i, 9000, true); assert.equal(run.phase, 'clear');
        const split = Math.floor(run.tape.length * (i === 3 ? 0.82 : 0.55));
        await p.evaluate(tape => window.springTest.replay(tape), run.tape.slice(0, split));
        await capture(p, `campaign-${i + 1}-middle`);
        await p.evaluate(tape => window.springTest.replay(tape), run.tape.slice(split));
        const actual = await state(p);
        assert.equal(actual.phase, 'clear'); assert.equal(actual.deaths, 0); assert.equal(actual.stars.length, 3);
        assert.ok(Math.abs(actual.time - run.time) < 0.02);
        await capture(p, `campaign-${i + 1}-clear`);
        if (i < 3) await p.getByRole('button', { name: `出发去 1-${i + 2}` }).click();
      }
      assert.equal((await state(p)).discovered.length, 7);
      await p.getByRole('button', { name: '回看春日地图' }).click();
      await capture(p, '08-map-complete');
      assert.equal(await p.locator('button:disabled').count(), 0);
      await p.keyboard.press('Escape');
      await p.getByRole('button', { name: '看看新朋友' }).click();
      await p.getByRole('button').filter({ hasText: '首播场务长' }).click();
      await capture(p, '09-complete-codex');
      await p.reload(); await p.getByRole('button', { name: '继续春日冒险' }).waitFor();
      assert.equal((await state(p)).unlocked, 3); assert.equal((await state(p)).discovered.length, 7);
      await p.getByRole('button', { name: '选择关卡', exact: true }).click();
      const best = await p.evaluate(() => window.springTest.state.save.best);
      assert.equal(best.reduce((n, v) => n + v.stars.length, 0), 12);
      await p.keyboard.press('Escape');
    }
    const mobile = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true });
    await mobile.route(/https:\/\/(pagead2\.googlesyndication\.com|hm\.baidu\.com)\//, r => r.fulfill({ body: '' }));
    await mobile.route(/\/api\/(record|demos\/visits)(\?|$)/, r => r.fulfill({ json: { success: true, count: 0 } }));
    await mobile.addInitScript(() => { if (window.speechSynthesis) window.speechSynthesis.speak = () => {}; });
    const m = await mobile.newPage(); m.on('pageerror', e => errors.push(e.message));
    await m.goto(`${base}${gamePath}?test=1`); await m.getByRole('button', { name: '把信寄出去' }).waitFor();
    await m.evaluate(() => window.springTest.manual(true));
    await m.getByRole('button', { name: '把信寄出去' }).tap();
    const cdp = await mobile.newCDPSession(m);
    const point = async name => { const b = await m.getByRole('button', { name, exact: true }).boundingBox(); assert.ok(b); return { x: b.x + b.width / 2, y: b.y + b.height / 2 }; };
    const right = await point('向右'); const jump = await point('跳跃');
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...right, id: 1 }, { ...jump, id: 2 }] });
    await m.evaluate(() => window.advanceTime(200)); const moved = await state(m); assert.ok(moved.player.x > 150 && moved.player.vy < 0);
    await capture(m, '05-mobile-landscape');
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
    await m.evaluate(() => window.advanceTime(100));
    assert.equal(await m.evaluate(() => window.springTest.state.player.jumpHeld), false);
    await m.setViewportSize({ width: 390, height: 844 }); await capture(m, '06-mobile-portrait');
    await m.getByRole('button', { name: '暂停或继续' }).tap();
    await m.getByRole('button', { name: '操作与设置' }).tap();
    await m.getByRole('button', { name: '轻松模式' }).tap();
    assert.equal(await m.evaluate(() => window.springTest.state.save.assist), true);
    await capture(m, '10-mobile-settings');
    await mobile.close();
    assert.deepEqual(errors, []);
  } finally { await browser.close(); fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify({ errors, captures }, null, 2)); }
  console.log(JSON.stringify({ passed: true, captures: captures.length, errors, out }));
})().catch(e => { console.error(e); process.exitCode = 1; });
