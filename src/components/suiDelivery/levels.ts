export function deliveryLevel(s: Pick<DeliveryGame, "levelId">): DeliveryLevel {
  return LEVELS.find((v) => v.id === s.levelId) || LEVELS[0];
}
export function levelSwitches(level: DeliveryLevel): string[] {
  return [...level.gates.map((gate) => gate.id), ...(level.rain?.hooks.map((hook) => hook.id) || []), ...(level.rain?.bird ? ["bird-ribbon"] : []), ...(level.theater?.hooks.map((hook) => hook.id) || []), ...(level.theater?.banquet ? ["banquet-served"] : [])];
}
export function levelUnlocked(save: DeliverySave, id: string): boolean {
  const i = LEVELS.findIndex((v) => v.id === id);
  return i === 0 || (i > 0 && save.delivered.includes(LEVELS[i - 1].id));
}
export function nextOrder(save: DeliverySave): DeliveryLevel {
  return (
    LEVELS.find((v) => !save.delivered.includes(v.id)) ||
    LEVELS[LEVELS.length - 1]
  );
}
