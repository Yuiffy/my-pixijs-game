export function translateResetText(value: string, locale: ResetLocale): string {
  if (locale === "zh" || !/[\u3400-\u9fff]/.test(value)) return value;
  // Edition names also occur inside combined configuration and calibration labels.
  const editionText = value.replaceAll("GPT-6.1 Astra · 虚构推演", "GPT-6.1 Astra · fictional");
  if (editionText !== value) return translateResetText(editionText, locale);
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.slice(leading.length, value.length - trailing.length);
  const direct = EN[core] ?? EN_DETAILS[core] ?? EN[` ${core}`] ?? EN_DETAILS[` ${core}`];
  if (direct) return `${leading}${direct}${trailing}`;
  for (const entry of EN_DYNAMIC) {
    const match = core.match(entry.test);
    if (match) return `${leading}${entry.render(match)}${trailing}`;
  }
  return value;
}

function translateNode(node: ReactNode, locale: ResetLocale): ReactNode {
  if (typeof node === "string") return translateResetText(node, locale);
  if (!isValidElement(node)) return node;
  const element = node as ReactElement<Record<string, unknown>>;
  const props: Record<string, unknown> = {};
  for (const name of ["title", "aria-label", "placeholder"]) {
    if (typeof element.props[name] === "string") props[name] = translateResetText(element.props[name], locale);
  }
  if (element.props.children !== undefined) {
    props.children = Children.map(element.props.children as ReactNode, (child) => translateNode(child, locale));
  }
  return Object.keys(props).length ? cloneElement(element, props) : element;
}

export function Translated({ children }: { children: ReactNode }) {
  const locale = useContext(ResetLocaleContext);
  return <>{Children.map(children, (child) => translateNode(child, locale))}</>;
}
